import Foundation

/// CoreBlow: Original implementation of Assistant Text Parser.
/// 1. Pattern borrowed: Extracting "think" vs "response" text segments from an AI model's output buffer by looking for `<think>` tags.
/// 2. Implemented differently: Uses `CoreBlowMessageSegmenter` with `Scanner`-based parsing for more robust, stateful text traversal.
/// This prevents recursive parsing crashes present in basic substring index tracking.
///
/// Example Usage:
/// ```
/// let segments = CoreBlowMessageSegmenter.segment(rawText: "<think>Planning...</think> Done!")
/// ```

// MARK: - Domain Models

/// Represents a distinct chunk of text generated by the AI model.
public struct CognitiveSegment: Identifiable, Equatable {

    /// Defines whether the segment is internal reasoning (hidden from user) or finalized output.
    public enum CognitiveState {
        case reasoning
        case finalized
    }

    public let id = UUID()
    public let state: CognitiveState
    public let content: String

    public init(state: CognitiveState, content: String) {
        self.state = state
        self.content = content
    }
}

// MARK: - Core Parser

public struct CoreBlowMessageSegmenter {

    // MARK: - Public API

    /// Parses raw model output into distinct reasoning and finalized text segments.
    /// - Parameters:
    ///   - rawText: The complete string emitted by the LLM.
    ///   - includeReasoning: Whether to return segments typed as `reasoning`. If false, they are omitted.
    /// - Returns: An ordered array of parsed segments.
    public static func segment(rawText: String, includeReasoning: Bool = true) -> [CognitiveSegment] {
        let cleanText = rawText.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !cleanText.isEmpty else { return [] }

        // Fast path: No XML tags means it's purely finalized text
        if !cleanText.contains("<") {
            return [CognitiveSegment(state: .finalized, content: cleanText)]
        }

        let parsedSegments = extractSegments(from: cleanText)

        if includeReasoning {
            return parsedSegments
        } else {
            return parsedSegments.filter { $0.state == .finalized }
        }
    }

    /// Returns only the finalized response segments, stripping out all reasoning/thinking blocks entirely.
    public static func finalizedSegments(from rawText: String) -> [CognitiveSegment] {
        return segment(rawText: rawText, includeReasoning: false)
    }

    /// Determines if there is actual content in the requested segment type. Useful for hiding empty UI bubbles.
    public static func containsContent(in rawText: String, checkReasoning: Bool = false) -> Bool {
        let segments = segment(rawText: rawText, includeReasoning: checkReasoning)
        return !segments.isEmpty
    }

    // MARK: - Internal Parsing Logic

    private static let thinkOpenTag = "<think>"
    private static let thinkCloseTag = "</think>"
    private static let finalOpenTag = "<final>"
    private static let finalCloseTag = "</final>"

    /// Scans the entire text linearly to construct accurate state-bounded segments.
    private static func extractSegments(from text: String) -> [CognitiveSegment] {
        var segments: [CognitiveSegment] = []
        let scanner = Scanner(string: text)
        scanner.charactersToBeSkipped = nil

        var currentState: CognitiveSegment.CognitiveState = .finalized

        while !scanner.isAtEnd {
            let startIndex = scanner.currentIndex

            // Search for the next potential tag boundary
            guard let nextTagIndex = text.range(of: "<", range: startIndex..<text.endIndex)?.lowerBound else {
                // No more tags, the rest is text for the current state
                let remaining = String(text[startIndex...])
                appendSegment(content: remaining, state: currentState, to: &segments)
                break
            }

            // Capture text before the tag
            if nextTagIndex > startIndex {
                let textBeforeTag = String(text[startIndex..<nextTagIndex])
                appendSegment(content: textBeforeTag, state: currentState, to: &segments)
            }

            scanner.currentIndex = nextTagIndex

            // Determine which tag we hit and change state machine mode
            if scanner.scanString(thinkOpenTag) != nil {
                currentState = .reasoning
            } else if scanner.scanString(thinkCloseTag) != nil {
                currentState = .finalized
            } else if scanner.scanString(finalOpenTag) != nil {
                currentState = .finalized
            } else if scanner.scanString(finalCloseTag) != nil {
                currentState = .finalized
            } else {
                // It was a < but not a recognized tag. Treat as normal text.
                scanner.currentIndex = text.index(after: nextTagIndex)
                appendSegment(content: "<", state: currentState, to: &segments)
            }
        }

        return segments
    }

    /// Appends a new segment to the array only if it contains visible non-whitespace characters.
    private static func appendSegment(content: String, state: CognitiveSegment.CognitiveState, to segments: inout [CognitiveSegment]) {
        let trimmed = content.trimmingCharacters(in: .whitespacesAndNewlines)
        if !trimmed.isEmpty {
            segments.append(CognitiveSegment(state: state, content: trimmed))
        }
    }

    // MARK: - OC-Compatible API Surface

    /// Parse raw model output into segments (OC-compatible name).
    public static func segments(from raw: String, includeThinking: Bool = true) -> [CognitiveSegment] {
        return segment(rawText: raw, includeReasoning: includeThinking)
    }

    /// Check whether raw text contains visible content after parsing (OC-compatible name).
    public static func hasVisibleContent(in raw: String, includeThinking: Bool) -> Bool {
        return containsContent(in: raw, checkReasoning: includeThinking)
    }

    /// Convenience: check for visible finalized content only.
    public static func hasVisibleContent(in raw: String) -> Bool {
        return hasVisibleContent(in: raw, includeThinking: false)
    }
}

