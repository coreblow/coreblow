#!/usr/bin/env node
/**
 * scripts/generate-plugin-sdk-facades.mjs
 * [PORT] coreblow-main
 *
 * Generates plugin-sdk facade files (re-exports) from extension API surfaces.
 * In CoreBlow, extensions live at src/extensions/<name>/api.ts.
 *
 * For channels without a @coreblow extension yet, this script prints a
 * TODO stub rather than overwriting hand-crafted adapters.
 *
 * Usage:
 *   node scripts/generate-plugin-sdk-facades.mjs
 *   node scripts/generate-plugin-sdk-facades.mjs --dry-run
 *   node scripts/generate-plugin-sdk-facades.mjs --channel telegram
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const SDK = resolve(ROOT, "src/plugin-sdk");
const EXT = resolve(ROOT, "src/extensions");

const isDryRun = process.argv.includes("--dry-run");
const channelFilter = (() => {
  const idx = process.argv.indexOf("--channel");
  return idx !== -1 ? process.argv[idx + 1] : null;
})();

// ─── Known extension mappings ────────────────────────────────────────────────
const CHANNEL_FACADES = [
  { channel: "telegram",  sdkFile: "telegram-account",         exports: ["resolveTelegramAccount"] },
  { channel: "telegram",  sdkFile: "telegram-allow-from",      exports: ["isNumericTelegramUserId", "normalizeTelegramAllowFromEntry"] },
  { channel: "telegram",  sdkFile: "telegram-surface",         apiFile: "api" },
  { channel: "telegram",  sdkFile: "telegram-runtime-surface", apiFile: "runtime-api" },
  { channel: "discord",   sdkFile: "discord-account",          exports: ["resolveDiscordAccount"] },
  { channel: "discord",   sdkFile: "discord-surface",          apiFile: "api" },
  { channel: "discord",   sdkFile: "discord-runtime-surface",  apiFile: "runtime-api" },
  { channel: "discord",   sdkFile: "discord-thread-bindings",  apiFile: "runtime-api" },
  { channel: "discord",   sdkFile: "discord-timeouts",         apiFile: "api" },
  { channel: "discord",   sdkFile: "discord-session-key",      exports: ["normalizeExplicitDiscordSessionKey"] },
  { channel: "slack",     sdkFile: "slack-account",            exports: ["resolveSlackAccount"] },
  { channel: "slack",     sdkFile: "slack-surface",            apiFile: "api" },
  { channel: "slack",     sdkFile: "slack-runtime-surface",    apiFile: "runtime-api" },
  { channel: "slack",     sdkFile: "slack-target-parser",      exports: ["parseSlackTarget", "resolveSlackChannelId"] },
  { channel: "whatsapp",  sdkFile: "whatsapp-surface",         apiFile: "api" },
  { channel: "whatsapp",  sdkFile: "whatsapp-targets",         apiFile: "api" },
  { channel: "signal",    sdkFile: "signal-surface",           apiFile: "api" },
  { channel: "matrix",    sdkFile: "matrix-surface",           apiFile: "api" },
  { channel: "matrix",    sdkFile: "matrix-helper",            apiFile: "api" },
  { channel: "matrix",    sdkFile: "matrix-runtime-surface",   apiFile: "runtime-api" },
  { channel: "matrix",    sdkFile: "matrix-thread-bindings",   apiFile: "api" },
];

const PROVIDER_FACADES = [
  "ollama", "openai", "deepseek", "openrouter", "amazon-bedrock",
  "xai", "together", "venice", "kilocode", "huggingface", "qianfan",
  "kimi-coding", "chutes", "byteplus", "volcengine", "litellm",
  "moonshot", "modelstudio", "opencode", "opencode-go", "sglang", "vllm",
  "mistral", "minimax", "nvidia", "google", "zai", "anthropic-vertex",
];

// ─── Main ──────────────────────────────────────────────────────────────────
let generated = 0;
let skipped = 0;
let missing = 0;

for (const facade of CHANNEL_FACADES) {
  if (channelFilter && facade.channel !== channelFilter) continue;

  const extApiPath = facade.apiFile
    ? resolve(EXT, facade.channel, `${facade.apiFile}.ts`)
    : null;

  const sdkPath = resolve(SDK, `${facade.sdkFile}.ts`);

  // Skip if extension API doesn't exist yet (use hand-crafted stub)
  if (extApiPath && !existsSync(extApiPath)) {
    console.log(`  SKIP  ${facade.sdkFile} — no extension at src/extensions/${facade.channel}/${facade.apiFile}.ts`);
    skipped++;
    continue;
  }

  // Skip if file already exists and was hand-crafted (not generated)
  if (existsSync(sdkPath)) {
    const content = readFileSync(sdkPath, "utf-8");
    if (!content.includes("Generated by scripts/generate-plugin-sdk-facades.mjs")) {
      console.log(`  KEEP  ${facade.sdkFile} — hand-crafted file preserved`);
      skipped++;
      continue;
    }
  }

  // Generate facade
  const relPath = extApiPath
    ? `../../extensions/${facade.channel}/${facade.apiFile}.js`
    : null;

  let content = `// Generated by scripts/generate-plugin-sdk-facades.mjs. Do not edit manually.\n`;

  if (relPath && facade.exports) {
    content += `export {\n${facade.exports.map(e => `  ${e},`).join("\n")}\n} from "${relPath}";\n`;
  } else if (relPath) {
    content += `export * from "${relPath}";\n`;
  }

  if (isDryRun) {
    console.log(`  DRY   ${facade.sdkFile}`);
  } else {
    writeFileSync(sdkPath, content, "utf-8");
    console.log(`  GEN   ${facade.sdkFile}`);
  }
  generated++;
}

console.log(`\nDone: ${generated} generated, ${skipped} kept/skipped, ${missing} missing extensions`);
console.log(`Run with --dry-run to preview without writing.`);
